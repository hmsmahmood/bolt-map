export type TranslationKey = keyof typeof messages.en;

@Injectable({ providedIn: "root" })
export class TranslationService {
  private readonly currentLocale = signal<AppLocale>(this.readLocale());
  readonly locale = this.currentLocale.asReadonly();

  text(key: TranslationKey): string {
    return messages[this.currentLocale()][key] ?? messages.en[key];
  }

  setLocale(locale: string): void {
    if (locale !== "en" && locale !== "ms" && locale !== "ta") {
      throw new Error(`Unsupported locale: ${locale}`);
    }

    this.currentLocale.set(locale);
    localStorage.setItem("gng-locale", locale);
    document.documentElement.lang = locale;
  }

  private readLocale(): AppLocale {
    const storedLocale = localStorage.getItem("gng-locale");
    if (
      storedLocale === "en" ||
      storedLocale === "ms" ||
      storedLocale === "ta"
    ) {
      document.documentElement.lang = storedLocale;
      return storedLocale;
    }

    return "en";
  }
}
